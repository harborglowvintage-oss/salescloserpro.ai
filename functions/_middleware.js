const MARKDOWN_TYPES = ['text/markdown', 'text/x-markdown']

export async function onRequest({ request, next, env }) {
  const url = new URL(request.url)
  const page = PAGES[url.pathname]
  if (!page || (request.method !== 'GET' && request.method !== 'HEAD')) return next()

  if (prefersMarkdown(request.headers.get('Accept'))) {
    try {
      const copy = await env.ASSETS.fetch(new Request(new URL(page.markdown, url)))
      if (copy.ok) return markdownResponse(await copy.text(), page, request.method === 'HEAD')
    } catch {
      // fall through to the HTML page
    }
  }

  const response = await next()
  try {
    return withPageHeaders(response, page)
  } catch {
    return response
  }
}

/*
 * True when the client rates text/markdown at least as highly as HTML. A browser, which asks
 * for text/html first and anything else at a lower weight, gets HTML; "Accept: text/markdown"
 * gets markdown; "text/markdown, text/html;q=0.9" gets markdown; no Accept header gets HTML.
 */
export function prefersMarkdown(accept) {
  if (!accept) return false
  let markdown = 0
  let html = -1
  let anyText = -1
  let any = -1
  for (const part of accept.toLowerCase().split(',')) {
    const [type, ...params] = part.split(';').map((s) => s.trim())
    let q = 1
    for (const param of params) {
      const [key, value] = param.split('=').map((s) => s.trim())
      if (key === 'q') {
        const n = Number.parseFloat(value)
        q = Number.isFinite(n) ? Math.min(Math.max(n, 0), 1) : 0
      }
    }
    if (MARKDOWN_TYPES.includes(type)) markdown = Math.max(markdown, q)
    else if (type === 'text/html') html = Math.max(html, q)
    else if (type === 'text/*') anyText = Math.max(anyText, q)
    else if (type === '*/*') any = Math.max(any, q)
  }
  const htmlQ = html >= 0 ? html : anyText >= 0 ? anyText : Math.max(any, 0)
  return markdown > 0 && markdown >= htmlQ
}

function markdownResponse(text, page, headOnly) {
  const headers = new Headers({ ...SHARED, ...page.headers })
  headers.set('Content-Type', 'text/markdown; charset=utf-8')
  headers.set('Content-Signal', CONTENT_SIGNAL)
  // Estimate, as Cloudflare's own conversion does: about four bytes per token.
  headers.set('x-markdown-tokens', String(Math.ceil(new TextEncoder().encode(text).length / 4)))
  // The page address stays the one to index and cite; the copy at /about.md is noindex.
  headers.set('Link', `<${page.canonical}>; rel="canonical"`)
  headers.set('Vary', 'Accept')
  return new Response(headOnly ? null : text, { status: 200, headers })
}

function withPageHeaders(response, page) {
  if (response.status >= 300 && response.status !== 304) return response
  const out = new Response(response.body, response)
  for (const [name, value] of Object.entries({ ...SHARED, ...page.headers })) out.headers.set(name, value)
  for (const name of REMOVE) out.headers.delete(name)
  const vary = out.headers.get('Vary')
  if (!vary || !vary.split(',').some((v) => v.trim().toLowerCase() === 'accept')) {
    out.headers.set('Vary', vary ? `${vary}, Accept` : 'Accept')
  }
  return out
}
