/**
 * salescloserpro.ai - reads public/_headers and public/_redirects the way Cloudflare Pages does,
 * so the build can copy headers into the Pages Function and check the routing.
 *   https://developers.cloudflare.com/pages/configuration/headers/
 *   https://developers.cloudflare.com/pages/configuration/redirects/
 *   https://developers.cloudflare.com/pages/functions/routing/#create-a-_routesjson-file
 */

/**
 * Where every app address is rewritten to: dist/app.html, the empty shell the app draws itself
 * into. Written without ".html" because Pages answers /app.html with a redirect to /app, and a
 * rewrite to it would send the visitor away from the address they asked for.
 */
export const APP_SHELL = '/app'

const BLOCK_START = '// BEGIN GENERATED by scripts/site/build.mjs from public/_headers. Edit _headers, then run: npm run site:sync'
const BLOCK_END = '// END GENERATED'
const MARKDOWN_LINK = /<([^>]+)>;\s*rel="alternate";\s*type="text\/markdown"/

/** _headers as rules in file order: { pattern, set: [[name, value]], detach: [name] }. */
export function parseHeaders(text) {
  const rules = []
  text.split(/\r?\n/).forEach((raw, i) => {
    const line = raw.trimEnd()
    const content = line.trim()
    if (!content || content.startsWith('#')) return
    if (!/^\s/.test(line)) {
      if (!content.startsWith('/')) throw new Error(`_headers line ${i + 1}: patterns must be paths starting with "/"`)
      rules.push({ pattern: content, set: [], detach: [] })
      return
    }
    const rule = rules.at(-1)
    if (!rule) throw new Error(`_headers line ${i + 1}: a header must follow a URL pattern`)
    if (content.startsWith('!')) {
      rule.detach.push(content.slice(1).trim())
      return
    }
    const colon = content.indexOf(':')
    if (colon < 1) throw new Error(`_headers line ${i + 1}: expected "Name: value"`)
    rule.set.push([content.slice(0, colon).trim(), content.slice(colon + 1).trim()])
  })
  return rules
}

/** _redirects as rules in file order: { from, to, status } (Pages defaults to 302). */
export function parseRedirects(text) {
  const rules = []
  text.split(/\r?\n/).forEach((raw, i) => {
    const content = raw.trim()
    if (!content || content.startsWith('#')) return
    const [from, to, status = '302', ...extra] = content.split(/\s+/)
    if (!to || extra.length || !/^\d{3}$/.test(status)) throw new Error(`_redirects line ${i + 1}: expected "from to [status]"`)
    rules.push({ from, to, status: Number(status) })
  })
  return rules
}

/** True when a Pages pattern matches the path. A * matches anything; a :name matches one segment. */
export function matches(pattern, path) {
  const source = pattern
    .split(/(\*|:[A-Za-z]\w*)/)
    .map((part) => (part === '*' ? '.*' : /^:[A-Za-z]/.test(part) ? '[^/]+' : part.replace(/[.+?^${}()|[\]\\]/g, '\\$&')))
    .join('')
  return new RegExp(`^${source}$`).test(path)
}

/**
 * The headers Pages sends for a path: every matching rule applies, in file order; a header set by
 * two rules gets both values joined with ", "; "! Name" removes a header.
 */
export function headersFor(rules, path) {
  const headers = new Map() // lower-case name -> [name as written, value]
  const detached = new Set()
  for (const rule of rules) {
    if (!matches(rule.pattern, path)) continue
    for (const name of rule.detach) {
      detached.add(name)
      headers.delete(name.toLowerCase())
    }
    for (const [name, value] of rule.set) {
      const previous = headers.get(name.toLowerCase())
      headers.set(name.toLowerCase(), previous ? [previous[0], `${previous[1]}, ${value}`] : [name, value])
    }
  }
  return { headers: Object.fromEntries(headers.values()), detached: [...detached] }
}

const header = (headers, name) => Object.entries(headers).find(([key]) => key.toLowerCase() === name.toLowerCase())?.[1]

/**
 * The pages that have a markdown copy: exact-path rules whose Link header points to one.
 * These are the pages the Pages Function answers for.
 */
export function markdownPages(rules) {
  return rules
    .filter((rule) => !/[*:]/.test(rule.pattern))
    .flatMap((rule) => rule.set
      .filter(([name, value]) => name.toLowerCase() === 'link' && MARKDOWN_LINK.test(value))
      .map(([, value]) => ({ path: rule.pattern, markdown: value.match(MARKDOWN_LINK)[1] })))
}

/** What the Pages Function needs to answer exactly as _headers would (see functions/_middleware.js). */
export function middlewareConfig(rules, siteUrl) {
  const pages = markdownPages(rules)
  if (!pages.length) throw new Error('public/_headers names no page with a markdown copy (Link: <…md>; rel="alternate"; type="text/markdown")')
  const full = pages.map((page) => headersFor(rules, page.path))
  const shared = Object.fromEntries(Object.entries(full[0].headers).filter(([name, value]) => full.every((f) => f.headers[name] === value)))
  const signals = new Set(pages.map((page) => header(headersFor(rules, page.markdown).headers, 'Content-Signal')))
  if (signals.size !== 1 || signals.has(undefined)) {
    throw new Error('public/_headers must give every markdown copy the same Content-Signal header (the /*.md rule)')
  }
  return {
    SHARED: shared,
    PAGES: Object.fromEntries(pages.map((page, i) => [page.path, {
      markdown: page.markdown,
      canonical: new URL(page.path, siteUrl).href,
      headers: Object.fromEntries(Object.entries(full[i].headers).filter(([name]) => !(name in shared))),
    }])),
    REMOVE: [...new Set(full.flatMap((f) => f.detached))],
    CONTENT_SIGNAL: [...signals][0],
  }
}

/** The generated block of functions/_middleware.js, as text. */
export function middlewareBlock(config) {
  const constants = Object.entries(config).map(([name, value]) => `const ${name} = ${JSON.stringify(value, null, 2)}`)
  return [BLOCK_START, ...constants, BLOCK_END].join('\n')
}

/** The middleware source with its generated block swapped for `block`. */
export function withMiddlewareBlock(source, block) {
  const start = source.indexOf(BLOCK_START)
  const end = source.indexOf(BLOCK_END)
  if (start < 0 || end < start || source.indexOf(BLOCK_START, start + 1) >= 0) {
    throw new Error('functions/_middleware.js must contain the generated block markers exactly once')
  }
  return source.slice(0, start) + block + source.slice(end + BLOCK_END.length)
}

/** _routes.json: run the Function only for the pages that have a markdown copy. */
export function routesJson(rules) {
  return { version: 1, include: markdownPages(rules).map((page) => page.path), exclude: [] }
}

/** Absolute paths declared as <Route path="…"> in App.jsx (the catch-all is left out). */
export function appRoutePaths(appSource) {
  return [...appSource.matchAll(/<Route\b[^>]*?\bpath="([^"]+)"/g)]
    .map(([, path]) => path)
    .filter((path) => path !== '*')
    .map((path) => `/${path.replace(/^\/+/, '')}`)
}

/**
 * Problems with the app routing: an app route with no rewrite to the app shell (it would get the
 * 404 page), or a rewrite for a route the app no longer has (it would get an empty app page).
 */
export function routingProblems({ routes, redirects, pagePaths }) {
  const sample = (route) => route.replace(/:[^/]+/g, 'x') // quotes/:id -> quotes/x
  const rewrites = redirects.filter((rule) => rule.status === 200 && rule.to === APP_SHELL)
  const problems = []
  for (const route of routes) {
    if (pagePaths.includes(route) || rewrites.some((rule) => matches(rule.from, sample(route)))) continue
    problems.push(`src/App.jsx route ${route} has no rewrite in public/_redirects. Add:  ${route.replace(/\/:.*$/, '/*')}  ${APP_SHELL}  200`)
  }
  for (const rule of rewrites) {
    if (!routes.some((route) => matches(rule.from, sample(route)))) {
      problems.push(`public/_redirects rewrites ${rule.from} to the app, but src/App.jsx has no such route`)
    }
  }
  return problems
}
